// Registers every character directory under src/characters/ by writing src/characters/generated.ts.
//
//   node scripts/gen-characters.mjs          write generated.ts (runs before build / dev / test)
//   node scripts/gen-characters.mjs --check  exit 1 if generated.ts is missing or stale
//
// The plugin is bundled into one main.js and runs on mobile (no `fs` at runtime), so "add a directory,
// get a character" has to happen at build time. Directories starting with "_" or "." are skipped.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const charDir = join(root, "src", "characters");
const outFile = join(charDir, "generated.ts");
const check = process.argv.includes("--check");

const ID = /^[a-z][a-z0-9_]*$/;
const REQUIRED = ["spec.ts", "persona.md"];

const errors = [];
const ids = readdirSync(charDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith("_") && !d.name.startsWith("."))
  .map((d) => d.name)
  .sort();

for (const id of ids) {
  if (!ID.test(id)) errors.push(`src/characters/${id}: directory name must match ${ID} (it is the character ID)`);
  for (const file of REQUIRED) {
    if (!existsSync(join(charDir, id, file))) errors.push(`src/characters/${id}: missing ${file}`);
  }
}
if (ids.length < 2) errors.push("src/characters: need at least two characters for a lineup");
if (errors.length) {
  for (const e of errors) console.error(`gen-characters: ${e}`);
  process.exit(1);
}

const lines = [
  "// Generated by scripts/gen-characters.mjs from the directories in src/characters/. Do not edit.",
  'import type { CharacterSpec } from "../types";',
  ...ids.map((id) => `import char_${id} from "./${id}/spec";`),
  "",
  "export const CHARACTER_SPECS: readonly CharacterSpec[] = [",
  ...ids.map((id) => `  char_${id},`),
  "];",
  "",
];
const content = lines.join("\n");
const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : null;

if (check) {
  if (current !== content) {
    console.error("gen-characters: src/characters/generated.ts is out of date; run `node scripts/gen-characters.mjs`");
    process.exit(1);
  }
} else if (current !== content) {
  writeFileSync(outFile, content);
  console.log(`gen-characters: registered ${ids.join(", ")}`);
}
